-- Identificador público y valoraciones del vendedor.
--
-- `public_id` es el número que va al final de la URL del anuncio, al estilo de
-- Wallapop: `/app/anuncio/monstera-deliciosa-1234`. El slug es decorativo y se
-- deriva del título; la búsqueda se hace por este entero, que es corto, único y
-- está indexado. Así el título puede cambiar sin romper enlaces.
--
-- `rating` y `review_count` viven en el perfil porque la tarjeta del anuncio los
-- pinta junto al vendedor. Nacen a 0: todavía no hay tabla de reseñas que los
-- calcule, y el seed los rellena con los valores del mock mientras el marketplace
-- sea de prueba.

alter table public.listings
	add column if not exists public_id bigint generated by default as identity;

do $$
begin
	if not exists (select 1 from pg_constraint where conname = 'listings_public_id_key') then
		alter table public.listings add constraint listings_public_id_key unique (public_id);
	end if;
end
$$;

alter table public.profiles
	add column if not exists rating numeric(2, 1) not null default 0,
	add column if not exists review_count integer not null default 0;
